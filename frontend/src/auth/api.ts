import { apiClient, type ApiResponse } from '../api/client'
import { ApiError } from '../api/errors'
import { retrySafeRequest } from '../api/retry'

export type AuthUser = {
  id: string
  email: string
  roles: string[]
  status: string
  email_verified: boolean
  timezone?: string
}

export type AuthSession = {
  access_token: string
  csrf_token: string
  token_type: string
  expires_in: number
  user: AuthUser
}

export type LoginCredentials = {
  email: string
  password: string
}

export type RegistrationResult = {
  id: string
  email: string
  roles: string[]
  status: string
  verification_status: string
}

type Envelope<T> = {
  data: T
}

function unwrap<T>(response: ApiResponse<Envelope<T>>): T {
  if (!response.data?.data) {
    throw new ApiError({
      status: response.status,
      code: 'invalid_response',
      message: 'The server returned an unexpected response.',
      headers: response.headers,
    })
  }
  return response.data.data
}

/**
 * Idempotency keys are generated by the caller so the same key can be reused
 * when retrying an identical operation. The shared API client does not
 * generate them automatically.
 */
export function createIdempotencyKey(): string {
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
    return crypto.randomUUID()
  }
  return `finpath-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`
}

export async function registerAccount(
  credentials: LoginCredentials,
  idempotencyKey = createIdempotencyKey(),
): Promise<RegistrationResult> {
  const response = await apiClient.post<Envelope<RegistrationResult>>(
    '/auth/register',
    credentials,
    { headers: { 'Idempotency-Key': idempotencyKey } },
  )
  return unwrap(response)
}

export async function requestVerificationEmail(
  email: string,
  idempotencyKey = createIdempotencyKey(),
): Promise<void> {
  await apiClient.post<Envelope<{ status: string }>>(
    '/auth/email-verification-requests',
    { email },
    { headers: { 'Idempotency-Key': idempotencyKey } },
  )
}

export async function consumeVerificationToken(
  token: string,
  idempotencyKey = createIdempotencyKey(),
): Promise<void> {
  await apiClient.post<Envelope<{ email_verified: boolean }>>(
    '/auth/email-verification/consume',
    { token },
    { headers: { 'Idempotency-Key': idempotencyKey } },
  )
}

export async function loginAccount(
  credentials: LoginCredentials,
): Promise<AuthSession> {
  const response = await apiClient.post<Envelope<AuthSession>>(
    '/auth/login',
    credentials,
    { credentials: 'include' },
  )
  return unwrap(response)
}

export async function fetchCsrfToken(): Promise<string> {
  // CSRF initialization is a safe GET. Retrying a cold-start failure cannot
  // rotate a refresh token or create a duplicate write.
  const response = await retrySafeRequest(() => (
    apiClient.get<Envelope<{ csrf_token: string }>>('/auth/csrf', {
      credentials: 'include',
    })
  ))
  return unwrap(response).csrf_token
}

export async function refreshSession(csrfToken: string): Promise<AuthSession> {
  const response = await apiClient.post<Envelope<AuthSession>>(
    '/auth/refresh',
    undefined,
    { credentials: 'include', csrfToken },
  )
  return unwrap(response)
}

export async function fetchCurrentUser(accessToken: string): Promise<AuthUser> {
  // Reading the current user is a safe GET. A cold-start retry cannot rotate
  // credentials or repeat a financial mutation.
  const response = await retrySafeRequest(() => (
    apiClient.get<Envelope<AuthUser>>('/auth/me', { accessToken })
  ))
  return unwrap(response)
}

export async function logoutSession(csrfToken: string): Promise<void> {
  await apiClient.post<void>('/auth/logout', undefined, {
    credentials: 'include',
    csrfToken,
  })
}
